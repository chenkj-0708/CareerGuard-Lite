import assert from "node:assert/strict";
import {canonicalScenarioUrl, scenarioIdForUrl, scanStatistics} from "../lib/scan-statistics.js";
const row=(id,scenarioId,totalLatencyMs,extra={})=>({id,scenarioId,totalLatencyMs,startedAt:`2026-11-05T00:00:${id.padStart(2,"0")}.000Z`,...extra});
const success=[row("02","a",100),row("03","a",100),row("04","a",100),row("05","b",500),row("06","a",9999,{evaluationOverride:true}),row("07","a",9999,{timingPhase:"warmup"}),row("08",null,10)];
const failures=[row("01","b",800,{failureCode:"INJECTION_FAILED"})];
const summary=scanStatistics(success,failures);
assert.equal(summary.independent_scenarios,2);assert.equal(summary.scenario_success_rate,.5);
assert.equal(summary.successful_scenarios,1);assert.equal(summary.failed_scenarios,1);
assert.equal(summary.scan_attempts,5);assert.equal(summary.repeated_attempts,3);
assert.equal(summary.mixed_outcome_scenarios,1);
assert.equal(summary.timing.success.median_ms,300);assert.equal(summary.timing.success.p95_ms,480);
assert.equal(summary.timing.failure.median_ms,800);
assert.deepEqual(summary.excluded,{forced:1,warmup:1,unidentified:1,duplicate_attempt:0});
assert.equal(scanStatistics([...success,success[0]],failures).excluded.duplicate_attempt,1);
assert.equal(scanStatistics([],[]).scenario_success_rate,null);
assert.equal(scanStatistics([row("01","a",NaN)],[]).timing.all.median_ms,null);
assert.equal(canonicalScenarioUrl("https://example.com/job?jk=123&utm_source=test#sol=abc"),"https://example.com/job?jk=123");
assert.equal(await scenarioIdForUrl("https://example.com/job?jk=123&ref=search"),await scenarioIdForUrl("https://example.com/job?jk=123"));
assert.notEqual(await scenarioIdForUrl("https://example.com/job?jk=123"),await scenarioIdForUrl("https://example.com/job?jk=456"));
assert.notEqual(await scenarioIdForUrl("https://example.com/#/job/123"),await scenarioIdForUrl("https://example.com/#/job/456"));
console.log("stable page identity, independent-case success and scenario-weighted median/p95 tests passed");
