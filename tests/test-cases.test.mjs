import assert from "node:assert/strict";
import {validateTestCases,matchTestCase,joinTestReferences,updateReferenceRationale} from "../lib/test-cases.js";
const item={scenarioId:"CG-001",url:"https://example.com/job?jk=1",groundTruth:"low",groupId:"G-1",split:"test",labelledAt:"2026-11-05T00:00:00Z"};
assert.throws(()=>validateTestCases([item,item]),/Duplicate/);
assert.throws(()=>validateTestCases([{...item,groundTruth:"safe"}]),/answer/);
assert.equal(matchTestCase([item],item.url+"&utm_source=test").scenarioId,item.scenarioId);
assert.throws(()=>matchTestCase([item],"https://example.com/job?jk=2",item.scenarioId),/different page/);
assert.throws(()=>matchTestCase([item],item.url,"CG-002"),/not registered/);
assert.throws(()=>matchTestCase([item,{...item,scenarioId:"CG-002"}],item.url),/Several/);
assert.equal(matchTestCase([item],item.url," CG-001 ").scenarioId,item.scenarioId);
const linkedin={...item,url:"https://www.linkedin.com/jobs/view/1234567890/?trackingId=abc&refId=share"};
assert.equal(matchTestCase([linkedin],"https://www.linkedin.com/jobs/view/1234567890/?trk=search",item.scenarioId).scenarioId,item.scenarioId);
assert.equal(matchTestCase([linkedin],"https://www.linkedin.com/jobs/search/?currentJobId=1234567890&keywords=engineer",item.scenarioId).scenarioId,item.scenarioId);
assert.throws(()=>matchTestCase([linkedin],"https://www.linkedin.com/jobs/view/9999999999/",item.scenarioId),/different page/);
assert.throws(()=>matchTestCase([linkedin],"https://www.linkedin.com/jobs/search/?keywords=engineer",item.scenarioId),/different page/);
assert.throws(()=>matchTestCase([linkedin],"https://linkedin.com.evil.example/jobs/view/1234567890/",item.scenarioId),/different page/);
const indeed={...item,url:"https://sg.indeed.com/viewjob?jk=abcdef123&from=shareddesktop"};
assert.equal(matchTestCase([indeed],"https://sg.indeed.com/jobs?q=engineer&vjk=abcdef123",item.scenarioId).scenarioId,item.scenarioId);
assert.throws(()=>matchTestCase([indeed],"https://sg.indeed.com/viewjob?jk=other123",item.scenarioId),/different page/);
assert.throws(()=>matchTestCase([item],"https://example.com/job?jk=1&unknown=2",item.scenarioId),/different page/);
const original={scenarioId:"CG-001",groundTruth:null,startedAt:"2026-11-05T00:00:01Z",baselines:{textOnly:{score:5,tier:"low"},metadataOnly:{score:5,tier:"low"},multiSignal:{score:5,tier:"low"}}};
const joined=joinTestReferences([original],[item])[0];
const reason=updateReferenceRationale(item,"  Clear duties and application steps.  ",item.labelledAt);
assert.equal(reason.rationale,"Clear duties and application steps.");
assert.equal(joinTestReferences([original],[{...item,...reason}])[0].reference.rationaleRecordedBeforePrediction,true);
assert.deepEqual(updateReferenceRationale({...item,...reason},reason.rationale,"2026-11-07T00:00:00Z"),reason);
const lateReason=updateReferenceRationale({...item,...reason},"Revised reason.","2026-11-07T00:00:00Z");
const lateJoined=joinTestReferences([original],[{...item,...lateReason}])[0];
assert.equal(lateJoined.reference.rationaleRecordedBeforePrediction,false);
assert.equal(lateJoined.reference.recordedBeforePrediction,true);
assert.equal(lateJoined.reference.labelledAt,item.labelledAt);
assert.equal(lateJoined.reference.rationale,"Revised reason.");
assert.equal(joined.reference.rationale,null);
assert.equal(joined.reference.rationaleRecordedBeforePrediction,false);
assert.throws(()=>updateReferenceRationale(item,"x".repeat(2001)),/2000/);
assert.equal(joined.groundTruth,"low");assert.equal(joined.reference.recordedBeforePrediction,true);
assert.equal(joined.referenceJoinStatus,"matched");assert.equal(original.groundTruth,null);
assert.deepEqual(joined.baselines,original.baselines);
assert.equal(joinTestReferences([original],[{...item,labelledAt:"2026-11-06T00:00:00Z"}])[0].reference.recordedBeforePrediction,false);
assert.equal(joinTestReferences([original],[{...item,groundTruth:null}])[0].referenceJoinStatus,"missing-label");
assert.equal(joinTestReferences([{...original,scenarioId:"other"}],[item])[0].referenceJoinStatus,"unregistered");
assert.throws(()=>joinTestReferences([{...original,groundTruth:"elevated"}],[item]),/conflict/);
assert.throws(()=>joinTestReferences([{...original,groupId:"other"}],[item]),/Group mismatch/);
assert.equal(joinTestReferences([{...original,failureCode:"CASE_MISMATCH"}],[item])[0].groundTruth,null);
console.log("registered case matching, human-reference joins, late labels and conflicts passed");
