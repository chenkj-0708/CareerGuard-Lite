import assert from "node:assert/strict";
import {validateTestCases,matchTestCase,joinTestReferences} from "../lib/test-cases.js";
const item={scenarioId:"CG-001",url:"https://example.com/job?jk=1",groundTruth:"low",groupId:"G-1",split:"test",labelledAt:"2026-11-05T00:00:00Z"};
assert.throws(()=>validateTestCases([item,item]),/Duplicate/);
assert.throws(()=>validateTestCases([{...item,groundTruth:"safe"}]),/answer/);
assert.equal(matchTestCase([item],item.url+"&utm_source=test").scenarioId,item.scenarioId);
assert.throws(()=>matchTestCase([item],"https://example.com/job?jk=2",item.scenarioId),/different page/);
assert.throws(()=>matchTestCase([item],item.url,"CG-002"),/not registered/);
assert.throws(()=>matchTestCase([item,{...item,scenarioId:"CG-002"}],item.url),/Several/);
const original={scenarioId:"CG-001",groundTruth:null,startedAt:"2026-11-05T00:00:01Z",baselines:{textOnly:{score:5,tier:"low"},metadataOnly:{score:5,tier:"low"},multiSignal:{score:5,tier:"low"}}};
const joined=joinTestReferences([original],[item])[0];
assert.equal(joined.groundTruth,"low");assert.equal(joined.reference.recordedBeforePrediction,true);
assert.equal(joined.referenceJoinStatus,"matched");assert.equal(original.groundTruth,null);
assert.deepEqual(joined.baselines,original.baselines);
assert.equal(joinTestReferences([original],[{...item,labelledAt:"2026-11-06T00:00:00Z"}])[0].reference.recordedBeforePrediction,false);
assert.equal(joinTestReferences([original],[{...item,groundTruth:null}])[0].referenceJoinStatus,"missing-label");
assert.equal(joinTestReferences([{...original,scenarioId:"other"}],[item])[0].referenceJoinStatus,"unregistered");
assert.throws(()=>joinTestReferences([{...original,groundTruth:"elevated"}],[item]),/conflict/);
assert.throws(()=>joinTestReferences([{...original,groupId:"other"}],[item]),/Group mismatch/);
assert.equal(joinTestReferences([{...original,failureCode:"CASE_MISMATCH"}],[item])[0].groundTruth,null);
console.log("registered case matching, human-reference joins, late labels and conflicts passed");
